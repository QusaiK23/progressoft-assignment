#!/bin/bash

echo "System Information"
echo "Executed By: $(whoami)"
echo "Hostname: $(hostname)"
echo "Server IP: $(hostname -I | awk '{print $1}')"
echo "Public IP: $(curl -s ifconfig.me)"
echo "OS Type and Version: $(lsb_release -ds 2>/dev/null || grep PRETTY_NAME /etc/os-release | cut -d'"' -f2)"
echo "Kernel Version: $(uname -r)"
echo "Architecture: $(uname -m)"
echo "Virtualization: $(systemd-detect-virt)"
echo "Server Time: $(date)"
echo "Timezone: $(timedatectl | grep "Time zone" | awk '{print $3, $4, $5}')"
echo "Uptime: $(uptime -p | sed 's/up //')"
echo ""
echo "Resource Usage"
echo "Total Memory: $(free -h --si | awk '/^Mem:/ {print $2}')"
echo "Memory Usage: $(free -h --si | awk '/^Mem:/ {print $3 " / " $2}')"
echo "Swap Usage: $(free -h --si | awk '/^Swap:/ {print $3 " / " $2}')"
echo "CPU Cores: $(nproc)"
